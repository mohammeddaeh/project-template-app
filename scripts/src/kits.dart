/// ما يحتاجه `kit.dart` و`setup_project.dart` و`check_structure.dart` من حِزَم
/// الأجهزة: البيان، وما المركَّب، وكيف يُكتب كلُّ ملفٍّ يمسّه التركيب.
///
/// **دوالٌّ على نصوص لا على ملفات** — فتُختبر جولةُ `add` ثم `remove` بلا قرص،
/// ويبقى الـIO بالسكربت وحده.
library;

import 'dart:convert';

const kitsDir = 'packages';
const kitsFile = 'lib/core/di/kits.g.dart';

/// بيانُ kit — `packages/kit_<name>/kit.json`.
class KitManifest {
  const KitManifest({
    required this.name,
    required this.register,
    required this.permissions,
    required this.platformPackages,
  });

  factory KitManifest.fromJson(String source) {
    final j = jsonDecode(source) as Map<String, dynamic>;
    return KitManifest(
      name: j['name'] as String,
      register: j['register'] as String,
      permissions: [...(j['permissions'] as List? ?? const []).cast<String>()],
      platformPackages: [
        ...(j['platformPackages'] as List? ?? const []).cast<String>(),
      ],
    );
  }

  /// `voice` — والحزمة `kit_voice`.
  final String name;

  /// دالّةُ التسجيل التي تصدّرها الحزمة: `void registerVoiceKit(GetIt getIt)`.
  final String register;

  /// أعلامُ الأذونات بـ`AppFeatures` (`microphone` · `camera`).
  final List<String> permissions;

  /// حزمُ المنصّة التي لا تُستورد إلا داخل الـkit (`C19`).
  final List<String> platformPackages;

  String get package => 'kit_$name';
}

// ── pubspec.yaml ─────────────────────────────────────────────────────────────

final _kitDep = RegExp(
  r'^  kit_(\w+):\s*\n    path: packages/kit_\w+\s*$',
  multiLine: true,
);

/// أسماءُ المركَّب — من `pubspec.yaml` وحده، فلا مصدرَ ثانٍ ينحرف عنه.
List<String> installedKits(String pubspec) => [
  for (final m in _kitDep.allMatches(pubspec))
    if (m[1] != 'contracts') m[1]!,
]..sort();

/// يضيف التبعية بعد `kit_contracts` — ولا شيء إن كانت موجودة.
String addKitDependency(String pubspec, String name) {
  if (installedKits(pubspec).contains(name)) return pubspec;
  const anchor = '  kit_contracts:\n    path: packages/kit_contracts\n';
  if (!pubspec.contains(anchor)) {
    throw StateError('kit_contracts غير موجود بـpubspec.yaml');
  }
  return pubspec.replaceFirst(
    anchor,
    '$anchor  kit_$name:\n    path: packages/kit_$name\n',
  );
}

String removeKitDependency(String pubspec, String name) =>
    pubspec.replaceFirst('  kit_$name:\n    path: packages/kit_$name\n', '');

// ── app_features.dart ────────────────────────────────────────────────────────

bool flagValue(String appFeatures, String flag) {
  final m = RegExp(
    'static const $flag = (true|false);',
  ).firstMatch(appFeatures);
  if (m == null) throw StateError('لا علَم `$flag` بـAppFeatures');
  return m[1] == 'true';
}

String setFlag(String appFeatures, String flag, bool value) {
  flagValue(appFeatures, flag); // يرمي إن غاب العلَم
  return appFeatures.replaceFirst(
    RegExp('static const $flag = (true|false);'),
    'static const $flag = $value;',
  );
}

// ── kits.g.dart ──────────────────────────────────────────────────────────────

/// ما أشعله التركيب من أعلام — يُقرأ من سطور `// kit:<name> enabled <flag>`.
///
/// `remove` يُطفئ **ما أشعله هو وحده** ولم تعد kit أخرى تحتاجه: علَمٌ كان
/// مُشعلاً قبل التركيب (الكاميرا لـ`MediaService`) يبقى كما هو.
Map<String, List<String>> enabledFlags(String kitsSource) {
  final out = <String, List<String>>{};
  for (final m in RegExp(
    r'^// kit:(\w+) enabled (\w+)$',
    multiLine: true,
  ).allMatches(kitsSource)) {
    (out[m[1]!] ??= []).add(m[2]!);
  }
  return out;
}

String renderKitsFile(
  List<KitManifest> installed,
  Map<String, List<String>> enabled,
) {
  final kits = [...installed]..sort((a, b) => a.name.compareTo(b.name));
  final b = StringBuffer()
    ..writeln('// GENERATED by scripts/kit.dart — do not edit by hand.')
    ..writeln('// The only file in lib/ that imports a device kit (C18).')
    ..writeln();
  for (final k in kits) {
    for (final flag in enabled[k.name] ?? const <String>[]) {
      b.writeln('// kit:${k.name} enabled $flag');
    }
  }
  b.writeln("import 'package:get_it/get_it.dart';");
  for (final k in kits) {
    b.writeln("import 'package:${k.package}/${k.package}.dart';");
  }
  b
    ..writeln()
    ..writeln('/// The device kits this app is built with.')
    ..writeln(
      'const installedKits = <String>[${kits.map((k) => "'${k.name}'").join(', ')}];',
    )
    ..writeln()
    ..writeln('void registerKits(GetIt getIt) {');
  for (final k in kits) {
    b.writeln('  ${k.register}(getIt);');
  }
  b.writeln('}');
  return b.toString();
}
