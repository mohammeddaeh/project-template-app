/// أينَ يذهب المستخدم **قبل أن يُرسم أول إطار**.
///
/// ## ولا شاشةَ سبلاش بفلاتر
///
/// كان بالقالب `SplashScreen`: مسارٌ أوّليّ يعرض الشعار، يتّخذ القرار، ثم
/// `replaceAll` إلى الوجهة. فيرى المستخدم **شعارَين متتاليَين** — شعارُ النظام
/// ثم شعارُ فلاتر — ولو تطابقا بالبكسل بقيَ بينهما **تلاشي النظام**، فيُقرأ
/// انتقالَين لا واحداً.
///
/// فصار القرار يقع بـ`main()` **قبل `runApp`**، وأوّلُ إطارٍ يرسمه فلاتر هو
/// الوجهةُ نفسُها. و`splash` النظام يبقى معلَّقاً طوال ذلك بحكم فلاتر — فما
/// يراه المستخدم: **شعارٌ واحد، ثم التطبيق**.
///
/// > 📌 **ووجهةٌ ثالثة تُضاف حين يحتاجها المشروع.** تطبيقٌ يعمل دون اتصال يحتاج
/// > غالباً `bootstrap`: جلسةٌ صالحة **وجهازٌ بلا بيانات** — والتوكن يبقى بعد
/// > إعادة تثبيتٍ وبعد مسح بيانات التطبيق، وكلاهما يترك جهازاً بلا صفٍّ واحد،
/// > فيمضي إلى الغلاف فتقول كلُّ شاشةٍ «لا يوجد اتصال» ولا شيء يقول للمستخدم
/// > إن عليه التنزيل.
enum StartupDestination {
  /// لا جلسة — أو جلسةٌ بلا هوية فأُنهيت.
  login,

  /// جلسةٌ صالحة.
  shell,
}
