/// إعدادات الموديول القابلة للتعديل بمشروعك — راجع
/// `lib/modules/session_guard/SETUP.md`.
abstract final class SessionGuardConfig {
  SessionGuardConfig._();

  /// مدّةُ الخمول/الخلفية التي تستوجب قفلاً عند العودة.
  ///
  /// **قياسها لا تخمينها لمشروعك**: تطبيقٌ مصرفي أو حكومي حسّاس يقصّرها إلى
  /// ثوانٍ؛ تطبيقٌ عام قد يوسّعها لدقائق. القيمة هنا افتراضٌ معقول لا قرار نهائي.
  static const Duration lockAfter = Duration(minutes: 2);

  /// عددُ محاولات رقم القفل الخاطئة قبل تسجيل خروجٍ كامل قسريّ.
  ///
  /// **لماذا تسجيل خروج لا قفلٌ مؤقّت**: رقمٌ من ٤-٦ خانات مساحة تخمينٍ صغيرة؛
  /// محاولاتٌ غير محدودة تجعله عديم الجدوى أمنياً. الخروجُ الكامل يُعيد
  /// المهاجم إلى نقطة الصفر (يحتاج كلمة المرور الحقيقية)، وقفلاً مؤقّتاً
  /// (٣٠ ثانية) لا يفعل شيئاً أمام محاولاتٍ آلية.
  static const int maxWrongAttempts = 5;
}
