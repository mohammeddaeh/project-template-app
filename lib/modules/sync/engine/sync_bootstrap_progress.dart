/// تقدّمُ الجرد الأوّل — **ما يُعرض للموظّف وهو واقفٌ ينتظر**.
///
/// ## ولماذا يُبلَّغ أصلاً
///
/// الإقلاع الأوّل هو اللحظة الوحيدة بعمر التطبيق التي **تُلزم** الموظّف بشبكة،
/// وقد تطول: تكليفٌ من ثلاثة محاضر يحمل مئات المقاسم. وشاشةٌ تدور بلا رقمٍ لا
/// يمكن التفريق فيها بين «يعمل ببطء» و«علِق» — فيُغلق التطبيق ويُعاد فتحه،
/// ويبدأ الجرد من أوّله.
///
/// ورقمٌ يتحرّك يحسم ذلك: «المقاسم — ١٤٠ صفّاً» تتغيّر كل ثانية تقول إن الطريق
/// مفتوح. ولا يُدّعى شريطُ نسبةٍ مئوية **على الصفوف**: الخادم لا يقول كم سيُرسل،
/// ونسبةٌ مُختلَقة تقفز من ١٠٪ إلى ١٠٠٪ أسوأ من عدّادٍ صادق.
///
/// ## وما أُضيف: الخطواتُ كلُّها لا الخطوةُ الجارية وحدها
///
/// كانت الشاشة تعرض **الجاريَ فقط** — اسمٌ ودوّار — فلا يعرف الواقف أمامها ما
/// تمّ ولا ما بقي، ولا أن «المقاسم» تأتي بعد «المحاضر». و[stages] تُعطيه
/// الخطّة كاملةً بكل بثّة، فيرسم الرسمُ صفّاً لكل خطوة بحالته: اكتمل · جارٍ ·
/// بانتظار.
///
/// و[subIndex]/[subCount] هما التقدّم **داخل** الخطوة: «محضر ٣ من ٨». وهذا
/// عددٌ يعرفه الجهاز فعلاً قبل أن يبدأ — عددُ المحاضر — فشريطُ نسبةٍ عليه
/// **ليس تخميناً**، بخلاف الصفوف.
class SyncBootstrapProgress {
  const SyncBootstrapProgress({
    required this.entityName,
    required this.entityIndex,
    required this.entityCount,
    required this.rows,
    required this.isEntityDone,
    this.stages = const [],
    this.subIndex = 0,
    this.subCount = 0,
    this.subLabel,
    this.subItems = const [],
    this.subDone = false,
  });

  /// اسمُ الكيان كما يعرفه العقد — `buildings` · `units` · `account`.
  ///
  /// **لا نصٌّ معروض.** الترجمة شأنُ الشاشة: الموديول لا يعرف لغة التطبيق ولا
  /// يجوز أن يبدأ، ونصٌّ يخرج من هنا يصل المستخدم بلا مرورٍ بملفَّي الترجمة.
  final String entityName;

  /// موضعُ الكيان بالترتيب، و[entityCount] كم هي جملةً — «٢ من ٣».
  final int entityIndex;
  final int entityCount;

  /// **خطواتُ الجرد كلُّها بترتيبها** — أسماءُ كياناتٍ لا نصوص، كـ[entityName].
  ///
  /// تُبثّ مع كل حدث ولا تتغيّر خلال الجرد الواحد، فالرسمُ يقرأ منها الخطة
  /// ويقرأ من [entityIndex] موضعَ الجاري: ما قبله تمّ، وما بعده ينتظر.
  final List<String> stages;

  /// كم صفّاً وصل **لهذه الخطوة** حتى الآن.
  final int rows;

  /// التقدّمُ داخل الخطوة — «محضر ٣ من ٨». و[subCount] صفرٌ لخطوةٍ لا تفصيل لها.
  final int subIndex;
  final int subCount;

  /// ما يُميّز الوحدة الجارية بداخل الخطوة — رقمُ المحضر (`mahdarNumber`).
  ///
  /// **قيمةُ بيانٍ لا نصٌّ مترجَم**: تُعرض كما وردت من الخادم، كما يُعرض أيُّ
  /// رقم محضرٍ بأي شاشة.
  final String? subLabel;

  /// **ما نزل داخل [subLabel] بأسمائه** — أرقامُ المقاسم التي كُتبت لذلك المحضر.
  ///
  /// تُملأ ببثّة [subDone] وحدها، وقيمُ بيانٍ كـ[subLabel] لا نصوصٌ مترجَمة.
  /// وهي ما تحوّل الشاشة من شريطٍ يتحرّك إلى **جردٍ يُقرأ**: «ضمن محضر ٢‑٢ نزل
  /// المقسم ١٠١ و١٠٢ و١٠٣». راجع `WatermarkProgress.unitNumbers`.
  final List<String> subItems;

  /// هل فرغت الوحدةُ الجارية داخل الخطوة (المحضر)؟ — البثّةُ الختامية له.
  ///
  /// و[isEntityDone] غيرُها: تلك تقول «فرغت الخطوة كلُّها»، وهذه «فرغ واحدٌ
  /// من ثمانية». وسطرُ الجرد يُضاف على هذه، فلو قُرئ من تلك لَما ظهر إلا سطرٌ
  /// واحد بنهاية كل شيء.
  final bool subDone;

  /// هل فرغت هذه الخطوة؟ يُبثّ مرّةً بنهايتها — بنجاحٍ أو إخفاق.
  final bool isEntityDone;
}

/// حصيلةُ الجرد الأوّل — **تُعاد ولا تُسجَّل وحدها**.
///
/// الدورة الخلفية تكتفي بسطر سجلّ لأن لا أحد ينتظرها. وهذه يقف أمامها
/// المستخدم: إخفاقٌ يُبتلَع هنا يعني إدخاله إلى تطبيقٍ **فارغٍ يبدو سليماً**،
/// ثم خروجه إلى الميدان بلا مقاسم يظنّ أنه حمّلها.
class SyncBootstrapResult {
  const SyncBootstrapResult({
    required this.rowsByEntity,
    required this.failedEntities,
  });

  /// ما وصل لكل كيانٍ نجح — والصفرُ جوابٌ صحيح («لا شيء مُسند بعد»).
  final Map<String, int> rowsByEntity;

  /// الكيانات التي لم تلحق. و`'*'` تعني أن الجرد لم يبدأ أصلاً — دورةٌ أخرى
  /// كانت جارية ولم تفرغ بالمهلة، أو القفل مأخوذ.
  final List<String> failedEntities;

  bool get isComplete => failedEntities.isEmpty;

  /// مجموعُ ما وصل — للسطر الختامي وحده، ولا يُبنى عليه قرار.
  int get totalRows => rowsByEntity.values.fold(0, (sum, rows) => sum + rows);
}
