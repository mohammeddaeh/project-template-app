/// **يحوّل صفَّ الخادم إلى الشكل الذي يخزّنه المحرّك** — واحدٌ لكل كيان.
///
/// ## لماذا واجهةٌ بالموديول لا استيرادٌ من الشريحة
///
/// سحبُ علامة المياه عمليةٌ واحدة قد تمسّ كيانين (سجلّاتٌ رئيسية وعناصرها):
/// نداءٌ يقول أيُّ سجلٍّ تغيّر، ثم نداءٌ لكلٍّ منها يقول أيُّ عنصرٍ تغيّر. ولا
/// موضعَ لها بـ`features/`: أيٌّ من الشريحتين تستضيفها تستوردُ الأخرى، و
/// `features → features ❌`.
///
/// وموضعُها بالموديول يصطدم بالعكس — `modules → features ❌` — لأنها تحتاج
/// **جدول مقابلة العقد** (`ItemDetailWire` مثلاً) وهو بيانُ شريحة لا بروتوكول.
///
/// فانفصل الأمران: الموديول يملك **متى يُسأل ومَن يُسأل**، والشريحة تملك
/// **كيف يُقرأ الجواب**. وهذا العقد هو الحدّ بينهما — يُصرَّح بالموديول،
/// ويُنفَّذ بالشريحة، ويُحلّ بالـDI باسم الكيان.
///
/// ```dart
/// @Named('itemsRowMapper')
/// @LazySingleton(as: SyncRowMapper)
/// class ItemsRowMapper implements SyncRowMapper { … }
/// ```
/// توقيعُ [SyncRowMapper.reconcile] مفرداً — يمرّره سحبُ علامة المياه
/// إلى `SyncPullMerger` بدل أن يعرف الأخيرُ بالمحوّلات شيئاً.
typedef SyncRowReconciler =
    Map<String, dynamic> Function(
      Map<String, dynamic> incoming,
      Map<String, dynamic> local,
    );

/// توقيعُ [SyncRowMapper.rekey] مفرداً — كـ[SyncRowReconciler] تماماً.
typedef SyncRowRekeyer =
    Map<String, dynamic> Function(Map<String, dynamic> row, String localId);

abstract class SyncRowMapper {
  /// اسمُ الكيان الذي يخدمه — نفسُ اسم `SyncFeatureContract.entityName`.
  String get entityName;

  /// صفُّ الخادم ⇐ صفُّ المخزن، أو `null` لصفٍّ لا هويّة له.
  ///
  /// **والمُخرَج يحمل المفاتيح الثلاثة التي يشترطها `SyncPullMerger`**:
  /// `id` و`updated_at` و`is_deleted`. وصفٌّ يخالفها يُسقَط بسطر تحذير —
  /// فيختفي من الشاشة بلا سببٍ ظاهر.
  ///
  /// و[serverTime] ختمُ الخادم لهذه اللقطة، يُستعمل حين لا يحمل الصفُّ ختماً
  /// خاصاً به: **وهو ليس اختراعَ ختم** — إنه ساعةُ الخادم لا ساعةُ هذا الهاتف.
  Map<String, dynamic>? toRow(
    Map<String, dynamic> raw, {
    required String serverTime,
  });

  /// **ما يبقى من الصفّ المحلّي حين يُكتب صفُّ الخادم فوقه.**
  ///
  /// يُنادى بـ`SyncPullMerger` قبل كل استبدال — [incoming] الوارد المبنيّ
  /// بـ[toRow]، و[local] الصفُّ المخزَّن المفكوك. والمُخرَج هو ما يُكتب.
  ///
  /// ## ولماذا خطافٌ لا استثناءٌ بالموديول
  ///
  /// المحرّك يستبدل الصفَّ استبدالاً كاملاً — وهو الصواب: الخادم صاحبُ
  /// الحقيقة. لكنّ **بعض العقود ناقصة**: حقلٌ يُدخله المستخدم ولا يملك الخادمُ
  /// موضعاً له ينزل غائباً بحكم الضرورة، لا لأنه مُسح. والاستبدال يمحوه، **بلا
  /// أن يُخفق شيء** — وهو أخطر ما بالمسار كلِّه.
  ///
  /// والموديول لا يعرف أيُّ حقلٍ كذلك — تلك معرفةُ شريحة. فيُصرَّح الخطاف هنا
  /// ويُنفَّذ هناك، كما [toRow] تماماً.
  ///
  /// **والافتراضيّ `incoming` كما هو** — وهو ما يعنيه «الخادم صاحب الحقيقة».
  /// فمن لا عقدَ ناقصاً له يكتب سطراً واحداً ولا يفكّر بالمسألة.
  Map<String, dynamic> reconcile(
    Map<String, dynamic> incoming,
    Map<String, dynamic> local,
  );

  /// **يجعل الصفَّ يقول المفتاحَ الذي سيُخزَّن تحته.**
  ///
  /// [toRow] يكتب `local_id` = معرّف الخادم، وهو الصواب للصفّ الذي يصل أوّلَ
  /// مرّة. لكنّ صفّاً **وُلد بالجهاز** له مفتاحٌ من صنعه، ويظلّ محفوظاً تحته بعد
  /// أن يعرفه الخادم — فيُكتب الوارد فوقه بمفتاحه هو (`SyncPullMerger`، سؤالُ
  /// `findByServerIds`).
  ///
  /// وبلا هذا الخطاف يقول العمودُ مفتاحاً ويقول الجسدُ آخر. والثمنُ ليس تجميلاً:
  /// الشاشاتُ تقرأ المعرّف **من الجسد** ثم تفتح الصفَّ به، فتسأل عن مفتاحٍ لا
  /// وجود له — **«العنصر غير موجود» على عنصرٍ بين يديك**.
  ///
  /// والموديول لا يعرف أين يسكن المعرّف بجسد صفٍّ بعينه — تلك معرفةُ شريحة،
  /// كـ[reconcile] حرفاً بحرف.
  Map<String, dynamic> rekey(Map<String, dynamic> row, String localId);
}
