import '../data/sync_cursor_store.dart';

/// **هل سُحب هذا الكيان إلى هذا الجهاز مرّةً على الأقل؟**
///
/// ## السؤال الذي لم يكن لأحدٍ جوابه
///
/// كل مغلِّفٍ محلّيٍّ‑أولاً بالمستودع يكتب هذا الشكل:
///
/// ```dart
/// final matches = local.items.where(...).toList();
/// if (matches.isNotEmpty) return Right(matches);
/// return inner.getSomething(...);   // ← الشبكة
/// ```
///
/// و**«فارغ» ليست جواباً واحداً**، بل جوابين لا يفرّق بينهما هذا السطر:
///
/// | المعنى | الصواب |
/// |---|---|
/// | «سُحب الكيان، ولا شيء يخصّ هذا المفتاح» | يُعرض فراغٌ مطمئن — ولا شبكة |
/// | «لم يُسحب بعد» | تُسأل الشبكة |
///
/// وخلطُهما يجعل **الحالة الطبيعية** — سجلٌّ بلا أبناء، وأبٌ بلا أولاد — تضرب
/// الشبكة بكل فتحة. وأوف‑لاين تفشل، فيرى الموظّف شاشة خطأ حيث يجب أن يرى «لا
/// توجد سجلات». وأونلاين تعمل، لكنها تدفع ثمن `InternetCheckerInterceptor`
/// كاملاً قبل أن تُجيب — بتطبيقٍ يُفترض ألّا يمسّ تنقّلُه الشبكةَ إطلاقاً.
///
/// ## ولا مؤشّر جديد يُخزَّن — الجواب موجود سلفاً
///
/// `SyncCursor.isBeginning` تعني «لم يُكتب مؤشّرٌ لهذا الكيان بعد»، و
/// `SyncEngine._pullEntity` لا يكتب المؤشّر إلا **بعد** أن يدمج صفحةً بنجاح.
/// فوجودُ مؤشّرٍ **هو** الإثبات بعينه: سحبٌ اكتمل مرّةً على الأقل.
///
/// وخزنُ علَمٍ ثانٍ بجانبه كان يعني حقيقتين لشيءٍ واحد — ويومَ تفترقان لن يقول
/// أيٌّ منهما إنها الخاطئة.
///
/// ⚠️ **ويُمحى مع مسح الحساب**: `SyncLocalDataWiper` يحذف `sync_meta` كاملاً،
/// فيعود الجواب `false` — وهو الصواب: جهازٌ مُسحت بياناته لم يُسحب إليه شيء.
class SyncHydration {
  const SyncHydration(this._cursors);

  final SyncCursorStore _cursors;

  /// `true` حين اكتمل سحبٌ واحدٌ على الأقل لهذا الكيان على هذا الجهاز.
  ///
  /// **والإخفاق يُقرأ `false`.** قاعدةٌ لا تُقرأ لا يجوز أن تُقنع المغلِّف بأن
  /// الفراغ الذي يراه كاملٌ وصادق — فتُعرض «لا توجد عناصر» لأبٍ فيه ثمانون.
  /// و`false` أسوأ ما تفعله أن تُرسل طلباً زائداً.
  Future<bool> isHydrated(String entityName) async {
    try {
      return !(await _cursors.read(entityName)).isBeginning;
    } catch (_) {
      return false;
    }
  }
}
