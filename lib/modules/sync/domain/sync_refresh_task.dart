/// **بيانٌ يملكه الخادم بالكامل، ولا مكان له بجدول الكيانات.**
///
/// ## المشكلة التي وُجد لها
///
/// `SyncPullExecutor` يخدم كياناً بمخزن المزامنة: صفوفٌ لها `local_id` وختمٌ
/// ونسخةٌ وشاهدةُ قبر. وثلاثةُ أشياء بهذا التطبيق ليست كذلك — قائمةُ
/// لوحُ حسابٍ، وهويّةُ مستخدم، وإعداداتٌ يملكها الخادم — فتبقى **خارج
/// الدورة كلياً**.
///
/// وكان بديلها أسوأ من غيابها: كلُّ مغلِّفٍ يُطلق `unawaited(_refreshQuietly())`
/// **بكل فتحةٍ لشاشته**. أي طلبُ شبكةٍ لا يحكمه `SyncGate` ولا يخنقه قفل ولا
/// يعرف بوجوده أحد — يجري لأن المستخدم ضغط تبويباً، ويتكرّر بكل رجوعٍ من
/// شاشةٍ فوقه.
///
/// | | دورةُ المزامنة | `_refreshQuietly` |
/// |---|---|---|
/// | البوّابة | `SyncGate` — توكن · تغطية · واي-فاي فقط · وصولُ الخادم | **لا شيء** |
/// | الخنق | قفلٌ مستديم + نافذةُ استقرار | **لا شيء** |
/// | متى | حدثٌ يستحقّ | **بكل `build`** |
///
/// ## والعقد
///
/// تُسجَّل بالـDI تحت هذا النوع (تسجيلٌ متعدّد كـ`SyncPullExecutor`)، ويناديها
/// المحرّك **بذيل الدورة الناجحة** بعد السحب وقبل الملفّات.
///
/// ```dart
/// @LazySingleton(as: SyncRefreshTask)
/// class RejectionsRefreshTask implements SyncRefreshTask { … }
/// ```
///
/// و[refresh] **لا ترمي ولا تُبلّغ**: لا شاشةَ تنتظرها، وإخفاقُها لا يُسقط بقيّة
/// الدورة. تكتب ما وصل وتصمت — وما بالجهاز يبقى معروضاً كما هو.
abstract class SyncRefreshTask {
  /// اسمٌ للسجلّ — يظهر بسطر الإخفاق فيُعرف أيُّها أخفق.
  String get name;

  Future<void> refresh();
}
