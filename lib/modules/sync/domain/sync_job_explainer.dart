import 'package:equatable/equatable.dart';

/// **ماذا سيصل الخادمَ من هذا الصفّ — وما الذي يحجز الباقي.**
///
/// منفذٌ تنفّذه الشريحةُ صاحبةُ الكيان، ويقرؤه من يعرض الطابور. ونظيرُ
/// `SyncExecutor` بالبنية: تسجيلٌ واحدٌ لكل كيان، يُقرأ بـ`allOf` ويُفهرَس
/// بـ[entityName].
///
/// ## ولماذا لا يجيب الموديولُ هذا السؤال بنفسه
///
/// لأنه **لا يملك جوابه**. الطابور يحمل حمولةَ JSON وصفّاً بالمخزن؛ و«هل يصعد
/// هذا القسم؟» حكمٌ يعرفه عقدُ الشريحة وحده — أيُّ حقلٍ إلزاميّ، وأيُّ حقلٍ لا
/// تقبله النقطة أصلاً، ومتى يُستبدل الكائن ولا يُدمج.
///
/// والبديلان كلاهما عطل: أن يخمّن الموديولُ (فيقول «سيُرفع» عمّا لن يُرفع)، أو
/// أن تنسخ شاشةُ المزامنة قواعدَ الشريحة (**R34** — نسختان تفترقان يوم
/// يُضاف حقلٌ إلزاميّ، `features → features ❌` كذلك).
///
/// ## وما يمنعه هذا العقد صراحةً: العمل الثقيل
///
/// [explain] تُنادى **بكل رسمةٍ للشاشة وبكل تغيّرٍ بالمخزن**. فلا يبني
/// المنفِّذُ جسدَ الطلب ولا يقرأ ملفاً ولا يرمّز بايتاً — يقرأ خريطةَ الصفّ
/// ويحكم. وترميزُ ستّ صورٍ base64 لرسم سطرٍ هو عشراتُ الميغابايتات من العمل
/// لعرضٍ يُغلق بعد ثانيتين. نفسُ سبب كون `SyncQueueReader.estimateBytes`
/// تقديراً لا قياساً.
///
/// ولذلك [SyncJobPartState.sending] تعني **«لُمس واكتمل ما يشترطه العقد»** لا
/// «وصل حتماً»: قيمةٌ قد تسقط لحظةَ التحويل (ملفٌّ اختفى من القرص مثلاً)، وذلك
/// يُقال بالسجلّ عند الرفع لا هنا.
abstract class SyncJobExplainer {
  /// اسمُ الكيان الذي يفسّره — يُفهرَس به، كـ`SyncExecutor.entityName`.
  String get entityName;

  /// [row] هو `data_json` مفكوكاً — بمفاتيح العقد مع الباك.
  ///
  /// وصفٌّ لا يُفهم يُردّ بقائمةٍ فارغة، لا برمية: الورقة تعرض ما تعرف وتصمت
  /// عمّا لا تعرف، ولا تُسقط الشاشة كلَّها لصفٍّ واحدٍ تالف.
  List<SyncJobPart> explain(Map<String, dynamic> row);

  /// **تراجعٌ عن عمليةٍ واحدة** — تُعيد الشريحةُ الحقلَ إلى ما يعرفه الخادم.
  ///
  /// ويُعيد **هل بقي بالصفّ ما ينتظر الرفع**: `false` تعني أن الصفَّ عاد
  /// مطابقاً لما عند الخادم، فيُسقط المستدعي وظيفتَه من الطابور
  /// (`SyncQueueRepository.cancelJob`).
  ///
  /// ## ⚠️ و«تراجع» تعني اتّفاقاً لا منعاً
  ///
  /// إسقاطُ الوظيفة وحدها — مع إبقاء القيمة الجديدة بالجهاز — يترك افتراقاً
  /// دائماً: شاشةُ المستخدم تقول شيئاً والخادمُ يقول غيرَه، **وأوّلُ سحبٍ يمرّ
  /// يمحو تعديله بلا إنذار** لأن الصفَّ صار «مُزامَناً». فالتراجع يُعيد القيمة
  /// أوّلاً، والإسقاطُ أثرٌ له.
  ///
  /// ويردّ `null` لِما لا يستطيع التراجعَ عنه — صفٌّ بلا لقطةِ خادم مثلاً —
  /// فتقول الشاشة ذلك بدل أن تَعِد بما لا يقع.
  Future<bool?> revert({
    required String localId,
    required String partKey,
    required String fieldKey,
  });

  /// **ماذا سيفعل [revertAll] بهذا الصفّ — بلا أن يفعله.**
  ///
  /// يُسأل لبناء الزرّ وحواره، فيقول الحوارُ ما سيقع بالضبط. وبلا هذا كان
  /// الحوارُ يَعِد بـ«عودةٍ إلى ما عند الخادم» ثم يمحو صفّاً لا يعرفه الخادم —
  /// فيضغطه المستخدم مطمئنّاً ويخسر عملَ ساعة.
  ///
  /// و[row] هو `data_json` مفكوكاً، كـ[explain]. وصفٌّ لا يُفهم يُردّ
  /// [SyncFullRevertKind.unavailable]: لا يُخمَّن فعلٌ لا رجعةَ فيه.
  SyncFullRevertKind planFullRevert(Map<String, dynamic> row);

  /// **تراجعٌ عن كلّ ما بالصفّ دفعةً واحدة** — لا عن حقلٍ بعينه.
  ///
  /// و[revert] تبقى لمن أراد إلغاء عمليةٍ واحدة ويُبقي البقيّة؛ وهذه لمن
  /// أراد أن يعود الصفُّ كما كان. وبلاها كان الطريقُ الوحيد ضغطَ ↩ على كلّ
  /// حقلٍ على حدة — وكلُّ ضغطةٍ تُعيد كتابة الصفّ وتُعيد بناء الطابور — أو
  /// صفّاً يبقى عالقاً أبداً حين لا يكون له ما يُتراجَع إليه أصلاً.
  ///
  /// يُعيد ما وقع فعلاً (وهو نفسُ ما وعد به [planFullRevert])، و`null` رفضاً.
  ///
  /// ⚠️ **ولا يُسقط الوظيفة بنفسه**: المستدعي يُسقطها بعده
  /// (`SyncQueueRepository.cancelJob`) — نفسُ قسمة العمل بـ[revert]، والسببُ
  /// أن الطابور يملكه الموديول والصفَّ تملكه الشريحة.
  Future<SyncFullRevertKind?> revertAll({required String localId});
}

/// **ما يفعله التراجعُ الكامل بصفّ** — جوابُ `planFullRevert` وحصيلةُ
/// `revertAll` معاً، فلا ينحرف الوعدُ عن الفعل.
enum SyncFullRevertKind {
  /// **للصفّ لقطةُ خادم** — فيعود إليها كاملاً. ولا يضيع شيءٌ: ما يُمحى هو
  /// تعديلٌ محلّيٌّ لم يقبله الخادم، والذي يعرفه الخادم يبقى كما هو.
  restore,

  /// **لا لقطةَ ولا معرّفَ خادم: لم يره الخادمُ قطّ** — فلا شيء يُعاد إليه،
  /// و«التراجع» هنا معناه الوحيد **محوُ الصفّ وملفّاته**.
  ///
  /// وهذه حالةُ سجلٍّ وُلد بالجهاز ورفضه الخادمُ حتى استُنفدت محاولاته: بلا
  /// هذا الفعل يبقى بالطابور أبداً، لا يصعد ولا يُزال.
  ///
  /// ⚠️ **ولا رجعةَ فيه** — فلا يقع إلا بحوار تأكيدٍ يقول ذلك صراحةً.
  discard,

  /// **لا يُنفَّذ** — ولا يُخمَّن.
  ///
  /// صفٌّ له `serverId` وليست له لقطة: الخادمُ يحمله ونحن لا نعرف ماذا يحمل
  /// عنه (اللقطةُ تُكتب بالسحب وحده). فمحوُه يُخفي عن صاحبه شيئاً قائماً
  /// هناك، وردُّه إلى «لقطةٍ» لا وجود لها مستحيل. والمخرج: **تنزيلُ البيانات
  /// أوّلاً** — فتصل اللقطة ويصير الفعل [restore].
  unavailable,
}

/// حالُ جزءٍ من الصفّ بالرفعة القادمة — **ثلاثةٌ لا اثنان**.
///
/// و[unchanged] هي الثالثة التي لم تكن، وغيابُها كان يجعل الشاشة تكذب بأصدق
/// الحالات: قسمٌ وصل الخادمَ سليماً ولم يلمسه أحد بعدها يُقرأ «سيُرفع» فيبدو
/// أن عملاً ينتظر، أو «محجوز» فيبدو أن شيئاً نقص — وهو لا هذا ولا ذاك.
enum SyncJobPartState {
  /// يخرج مع الطلب القادم: لُمس، واكتمل ما يشترطه العقد.
  sending,

  /// لُمس ولم يكتمل — و[SyncJobPart.missingKeys] تقول بماذا.
  held,

  /// لم يتغيّر منذ آخر رفعةٍ ناجحة، فلا شيء يُرسَل عنه.
  unchanged,
}

/// جزءٌ واحد من الصفّ — قسمٌ بالاستمارة، أو مجموعةُ حقولٍ تُرفع معاً.
class SyncJobPart extends Equatable {
  const SyncJobPart({
    required this.key,
    required this.state,
    this.missingKeys = const [],
    this.operations = const [],
  });

  /// مفتاحُه بالعقد (`basic` · `type` …) — والعرضُ يترجمه، فلا نصَّ واجهةٍ هنا.
  final String key;

  final SyncJobPartState state;

  /// **ما ينقصه** بمفاتيح العقد — فارغةٌ لغير [SyncJobPartState.held].
  ///
  /// وهي الجوابُ الذي لم يكن موجوداً: «القسم الأول محجوز» وحدها تُقرأ عطلاً،
  /// و«محجوز — ينقصه العنوان والصور» تُقرأ عملاً باقياً.
  final List<String> missingKeys;

  /// **العملياتُ التي أجراها المستخدم على هذا الجزء** — فعلٌ لكلِّ حقل.
  ///
  /// وهي جوابُ «ماذا فعلتُ؟» لا «ماذا سيُرسَل»: النقطة قد تستبدل الجزء كاملاً
  /// وإن لم يتبدّل منه إلا حقل. فتقول الورقة «أُلغي مخطَّط المساحة» ويصعد القسم
  /// كلُّه — وهما صادقان معاً.
  ///
  /// وفارغةٌ لصفٍّ بلا لقطةِ خادم: لا تُخترع عمليةٌ لا تُعرف.
  final List<SyncJobOp> operations;

  @override
  List<Object?> get props => [key, state, missingKeys, operations];
}

/// **فعلٌ واحد على حقلٍ واحد** — وهو ما يُعرض وما يُتراجَع عنه.
class SyncJobOp extends Equatable {
  const SyncJobOp({required this.key, required this.kind});

  /// مفتاحُ الحقل بالعقد — والعرضُ يترجمه، فلا نصَّ واجهةٍ هنا.
  final String key;

  final SyncJobOpKind kind;

  @override
  List<Object?> get props => [key, kind];
}

/// **ثلاثةُ أفعالٍ لا حالات** — «أُضيف» و«عُدِّل» و«أُلغي».
///
/// والفرق بينها وبين «تغيّر» أنها تقول **ما فعله الإنسان**، فتُقرأ كما يتذكّره
/// ويُتراجَع عنها بثقة: من ألغى اختياراً يعرف أنه ألغاه، ولا يعرف أن حقلاً
/// «تغيّر».
enum SyncJobOpKind { added, edited, cleared }
