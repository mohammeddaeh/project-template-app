/// **ما تشير إليه صفوفُ الجهاز من ملفّاتِ الخادم — جرداً تقرؤه دورةُ المزامنة.**
///
/// ## العطل الذي وُجد له
///
/// السحبُ ينزّل **الصفوف** وحدها: حقولُ الملفّات تنزل مسارَ تخزينٍ نصّاً
/// (`storage\files\1787…png`) لا بايتات. و`ServerFileCache` **بلا تنزيلٍ
/// مسبق** بقرار — الضغطةُ هي ما يُنزِّل. فمن ضغط «تنزيل بياناتي» بالمكتب ومضى
/// إلى الميدان يجد صورةَ الهوية وعقدَ الإيجار **سطراً يُقرأ ولا يُرى**: البيانُ
/// نزل والمرفقاتُ لم تنزل، ولا شيء بالشاشة قال ذلك.
///
/// ## والعقد: الشريحةُ تقول أين ملفّاتُها، والموديول ينزّلها
///
/// `modules → features ❌`، فالموديول لا يعرف أن بالجهاز «مقاسم» ولا أين تسكن
/// مساراتُها بالصفّ. تُسجَّل الشريحةُ تحت هذا النوع (تسجيلٌ متعدّد كـ
/// `SyncPullExecutor`)، ويقرأ [MediaPrefetchManager] الجردَ منها:
///
/// ```dart
/// @LazySingleton(as: SyncMediaCatalog)
/// class NotesMediaCatalog implements SyncMediaCatalog { … }
/// ```
///
/// ⚠️ **ولا تُصفّي ما نزل**: الجردُ **كلُّ** ما تشير إليه الصفوف، والمنفّذ وحده
/// يسأل المخزنَ أيُّها بالجهاز. وتصفيةٌ بالشريحة تعني قاعدتين لسؤالٍ واحد
/// (R34) — وأسوأُ منها: شريحةٌ تنسى مساراً نزل فتُعيد تنزيله بكل دورة.
abstract class SyncMediaCatalog {
  /// اسمٌ للسجلّ — يظهر بسطر الإخفاق فيُعرف أيُّ جردٍ أخفق.
  String get name;

  /// كلُّ ما تشير إليه صفوفُ هذه الشريحة، **مجموعاً بمالكه**.
  Future<List<SyncMediaTarget>> targets();
}

/// **ملفّاتُ صفٍّ واحد — ومَن هو، بأرقامٍ يقرؤها المستخدم.**
///
/// والتجميع ليس ترتيباً: الشاشةُ تقول «يُنزَّل الآن — <الأب> · <الابن>»،
/// وقائمةُ مساراتٍ عارية لا تقول ذلك. فيُنزَّل صفٌّ صفّاً، ويُعرف أين وصل.
class SyncMediaTarget {
  const SyncMediaTarget({
    required this.ownerId,
    required this.paths,
    this.groupNumber,
    this.itemNumber,
  });

  /// معرّفُ الصفّ المحلّي — للسجلّ وحده، ولا تُبنى عليه ملاحة.
  final String ownerId;

  /// مساراتُ التخزين كما نزلت من الخادم — تُمرَّر إلى `ServerFileCache` كما هي.
  final List<String> paths;

  /// **قيمتا بيانٍ لا نصّان مترجَمان** — رقمُ الأب ورقمُ الصفّ.
  ///
  /// نفسُ عقد `SyncBootstrapProgress.subLabel`: الموديول لا يعرف لغة التطبيق،
  /// ونصٌّ يخرج من هنا يصل المستخدم بلا مرورٍ بملفَّي الترجمة. والشاشةُ تبني
  /// «<الأب> X · <الصفّ> Y» بمفاتيحها.
  final String? groupNumber;
  final String? itemNumber;
}
