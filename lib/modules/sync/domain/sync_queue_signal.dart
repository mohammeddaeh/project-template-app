import 'dart:async';

/// **جرسٌ يُقرع حين يدخل عملٌ الطابور.**
///
/// ## ولماذا وُجد — والمؤقّتُ الذي حلّ محلَّه
///
/// كان المحرّك يستيقظ بمؤقّتٍ دوريّ كل خمس دقائق: يسأل الطابور «هل من جديد؟»
/// ويكاد لا يجد شيئاً. سؤالٌ بلا سبب، تسعةٌ وتسعون بالمئة منه بلا جواب —
/// وبتطبيقٍ ميدانيّ على بيانات الجوّال ذلك بطاريةٌ وحزمةٌ تُنفقان على العدم.
///
/// والحقيقة أن **دخولَ الطابور حدثٌ يعرفه الكاتب لحظةَ وقوعه**. فبدل أن يُسأل
/// عنه، يُعلَن.
///
/// ```
/// حفظُ سجلّ ──► SyncWriteGateway ──► صفٌّ بالطابور ──► notify()
///                                                        │
///                                       SyncController ◄─┘  ──► دورة (بعد خنق)
/// ```
///
/// ## والخنقُ شرطٌ لا تحسين
///
/// حفظُ استمارةٍ واحدة يكتب السجلَّ وأبناءَه ومرفقاتِه — عشرةُ صفوفٍ بالطابور
/// خلال أجزاء من الثانية. وبلا نافذةٍ تجمعها تصير عشرَ دوراتٍ متتابعة، تسعٌ
/// منها تجد القفل مأخوذاً وتنصرف. راجع `SyncController`.
class SyncQueueSignal {
  final _controller = StreamController<void>.broadcast();

  Stream<void> get stream => _controller.stream;

  /// يُنادى من `SyncWriteGateway` بعد كل صفٍّ يدخل الطابور.
  void notify() {
    if (_controller.isClosed) return;
    _controller.add(null);
  }

  Future<void> dispose() => _controller.close();
}
