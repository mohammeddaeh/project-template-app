import 'package:get_it/get_it.dart';

/// **`getAll` بلا رمية على نوعٍ لا تسجيلَ له.**
///
/// ## العطل الذي يمنعه هذا الملف
///
/// `GetIt.getAll<T>()` **يرمي** حين لا يجد شيئاً:
///
/// ```
/// StateError: GetIt: No Objects/factories with type SyncExecutor
///             are not registered inside GetIt.
/// ```
///
/// وهذا خلافُ ما يبدو من `_Scope.getAll` الداخلي — ذاك يُعيد قائمةً فارغة،
/// **والعلنيُّ يلفّه بـ`throwIf(instances.isEmpty, …)`**. والفرق لا يظهر ما دام
/// ثمّة تسجيلٌ واحد، فيمرّ الكود سنينَ ثم يرمي يوم يُحذف آخرُ منفّذ.
///
/// مثالُه: مشروعٌ **يسحب ولا يدفع** يسأل `getAll<SyncExecutor>().isEmpty` —
/// والجوابُ المطلوب (`صفر`) هو بالضبط ما يرميه. فيُخفق `SyncSDK.initialize`
/// كلُّه، و**يُعطَّل الموديول بينما علَمُه مُشعَل**: لا محوّلات، ولا جرد،
/// وشاشاتٌ تقرأ الشبكة بتطبيقٍ صُمّم ليقرأ القاعدة.
///
/// ## القاعدة
///
/// **أيُّ `getAll<T>()` على نوعٍ قد يكون بلا تسجيل يمرّ من هنا.** و«قد يكون»
/// أوسعُ ممّا يبدو: منفّذُ دفعٍ يُحذف، ومهمّةُ تحديثٍ تُلغى، ومحوّلُ شريحةٍ
/// يُنقل.
///
/// و`isRegistered<T>()` **ليست البديل**: تقرأ التسجيلات غير المسمّاة وحدها
/// (راجع `lib/modules/sync/SETUP.md` §«واحدٌ بلا `@Named`»)، فتُجيب `false`
/// على نوعٍ كلُّ تسجيلاته مسمّاة — وهو الفخُّ المعاكس.
extension GetItGetAllOrEmpty on GetIt {
  /// كلُّ ما سُجِّل تحت [T] — **مسمّاه وغيرَ مسمّاه**، وقائمةٌ فارغة حين لا شيء.
  List<T> allOf<T extends Object>() {
    try {
      return getAll<T>().toList();
    } on StateError {
      // **`StateError` وحدها تُبتلع**: هي ما يرميه `throwIf` عند الفراغ.
      // ورميةٌ من مُنشئ أحد الكائنات نوعُها آخر، وابتلاعُها يُخفي عطلاً
      // حقيقياً خلف «لا شيء مسجَّل».
      return const [];
    }
  }
}
