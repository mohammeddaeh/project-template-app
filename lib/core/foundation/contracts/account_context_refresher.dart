/// **جلبُ سياق حساب المستخدم من الخادم** — `GET /show-user/me`.
///
/// ## لماذا عقدٌ بـ`foundation/` وليس نداءً مباشراً
///
/// اللحظتان اللتان تحتاجانه — **تسجيلُ الدخول** و**فتحُ التطبيق** — تسكنان
/// `features/auth/login/` و`features/startup/`، والجالبُ يسكن
/// `features/account/`. و`features → features` ممنوع بلا استثناء
/// (`lib/features/CLAUDE.md` §الاستثناءات). فالعقد هنا هو ما يجعل الشريحتين
/// تطلبان الفعل بلا أن تعرفا من ينفّذه — نفس نمط `SyncRefreshTask`.
///
/// ## وما لا يفعله
///
/// **لا يُخفق ولا يُعيد شيئاً.** جلبٌ يقع بالخلفية بجوار فعلٍ آخر (دخولٌ نجح،
/// تطبيقٌ فُتح) لا يجوز أن يُسقط ذلك الفعل: بلا تغطيةٍ تبقى اللقطة المحفوظة هي
/// المعروضة، وهو المخرج الصحيح. ومَن يحتاج النتيجة — تبويب «حسابي» — يسأل
/// `AccountOverviewRepository.getOverview()` مباشرةً.
abstract class AccountContextRefresher {
  /// يسحب من الخادم ويكتب النسخة المحلية. يبتلع كل إخفاق.
  Future<void> refresh();
}
