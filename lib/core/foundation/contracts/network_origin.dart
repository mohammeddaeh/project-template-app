import 'dart:async';

/// **مِن أين خرج هذا الطلب؟** — وسمٌ يُحمَل بمنطقة التنفيذ لا بوسيطٍ يُمرَّر.
///
/// ## القاعدة التي يحرسها
///
/// **التنقّل لا يمسّ الشبكة**: تُقرأ الشاشات من الجهاز، والمنافذُ إلى الخادم
/// **مسمّاةٌ ومعدودة** — دورةُ المزامنة، والدخول، والجردُ الأوّل، ومرفقٌ يطلبه
/// المستخدم بإصبعه، وسياقُ الحساب. ولا شيءَ غيرها.
///
/// > ⚠️ **وهذه سياسةٌ يختارها التطبيق لا قانونٌ يفرضه القالب.** تطبيقٌ يقرأ من
/// > الشبكة بكل شاشة لا يحتاج هذا الوسم أصلاً — والحارسُ عندئذٍ ضجيجٌ يُطفأ
/// > بحذف [NetworkOriginInterceptor] من سلسلة Dio. **وأمّا التطبيق المحلّيُّ
/// > الأولوية فلا يقوم بلاه**: القاعدةُ فيه شرطُ صحّةٍ لا تفضيلاً.
///
/// وتلك قاعدةٌ **بلا فاحصٍ تعود انضباطاً، والانضباط يُنسى**: سطرُ
/// `unawaited(_refreshQuietly())` واحدٌ بمغلِّفٍ لا يقرؤه أحد يُعيد الحال كما
/// كان، ولا يُخفق شيء — الشاشة تعمل، والاختبارات خضراء، والطلبات تتضاعف بصمت.
///
/// ## ولماذا منطقةٌ لا علَمٌ ساكن
///
/// عَلَمٌ ساكن (`static String? current`) يكذب: الدورة تُطلق `await`، وطلبُ
/// شاشةٍ يقع أثناءها يقرأ العَلَم موسوماً فيمرّ. أمّا `Zone` **فتُورَّث عبر
/// `await` إلى ما بدأ داخلها وحده** — فما بدأ خارجها لا يرثها مهما تزامنا.
///
/// ```dart
/// await NetworkOrigin.run(NetworkOrigin.sync, () => engine.runPendingJobs());
/// ```
abstract final class NetworkOrigin {
  NetworkOrigin._();

  static const _key = #networkOrigin;

  /// دورةُ المزامنة — دفعٌ وسحبٌ وتحديثٌ ورفعُ ملفّات.
  static const sync = 'sync';

  /// تسجيلُ الدخول والخروج وتجديدُ التوكن — بحكم التعريف.
  static const auth = 'auth';

  /// الجردُ الأوّل — اللحظة الوحيدة بعمر التطبيق التي تُلزم بشبكة.
  static const bootstrap = 'bootstrap';

  /// تنزيلُ مرفقٍ **طلبه المستخدم بإصبعه** — لا تنزيلٌ مسبق.
  static const userFile = 'user-file';

  /// سياقُ حساب المستخدم — من هو، وما دورُه وصلاحياتُه — **بلحظاتٍ معدودة**:
  /// عند تسجيل الدخول، وبكل فتحةٍ للتطبيق، وبضغطةِ تبويبِ الحساب.
  ///
  /// ⚠️ **وحدُّه لحظاتٌ معدودة لا «كلُّ فتحةِ شاشة»** — والفرقُ هو نفسُه الذي
  /// وُلدت منه هذه القاعدة: بيانُ الحساب يتبدّل نادراً، وسؤالُه بكل بناءٍ يجعل
  /// التنقّلَ يمسّ الشبكة.
  static const account = 'account';

  /// وسمُ المنطقة الجارية، أو `null` لطلبٍ خرج من شاشة.
  static String? get current => Zone.current[_key] as String?;

  /// يُجري [body] بمنطقةٍ موسومة — وكلُّ ما يبدأ داخلها يرث الوسم.
  static Future<T> run<T>(String origin, Future<T> Function() body) =>
      runZoned(body, zoneValues: {_key: origin});
}
