/// يمحو **كل ما يخصّ حساباً** من هذا الجهاز.
///
/// ## العطل الذي وُلد منه هذا العقد
///
/// الخروجُ كان يمسح الجلسة وحدها: `SessionRepository.clearSession()` و
/// `CurrentUserRepository.clear()`. وما عداهما يبقى كما هو —
/// `synced_entities` · `sync_queue` · `attachments` · بايتاتُ الصور بالتخزين
/// الخاص · المؤشّرات · اللقطات الثلاث.
///
/// فمستخدمٌ ثانٍ يدخل على نفس الجهاز:
///
/// | ما يراه | لماذا |
/// |---|---|
/// | مقاسمُ الأول بقوائمه | `SyncEntityStore.readTyped` يقرأ الجدول لا الحساب |
/// | صورُ الأول بمعرضه | `AttachmentFileStore` معنونٌ بالمحتوى لا بالمالك |
/// | **وطابورُ الأول يُدفع بتوكن الثاني** | `SyncEngine` يدفع ما بالجدول، ولا يسأل من كتبه |
///
/// والثالث ليس تسرّبَ عرضٍ بل **إسنادُ عملٍ إلى من لم يعمله**: مسحُ موظّفٍ يصل
/// الخادمَ باسم زميله.
///
/// و`SyncCursorStore.clearAll` و`SyncCycleStamp.clear` كانتا مكتوبتين لهذا
/// الغرض حرفياً — **وبلا مستدعٍ واحد** (R28).
///
/// ## ولماذا يسكن `foundation/` لا الموديول
///
/// المستدعون هم من يُتلفون — الخروج، وتبديل الحساب — ويعيشون بـ`features/`
/// و`core/`، وكلاهما لا يستورد `modules/`. فالتبعية تُقلَب: الواجهة تُعلَن هنا،
/// ومن يملك بياناتٍ يُنفّذها. نفس شكل [UnsyncedWorkProbe] وللسبب نفسه.
///
/// ## والافتراضي صادقٌ لا فارغ
///
/// [NoLocalDataWiper] يُسجَّل بـ`injection_module.dart` ولا يفعل شيئاً، لأن
/// تطبيقاً بلا موديول أوف‑لاين **لا يحمل بياناتٍ محلية أصلاً**. و
/// `registerSyncCore` يستبدله بمن يمحو فعلاً. فلا يحتاج المستدعي أن يسأل «هل
/// المزامنة مُشعَلة؟» — وهو سؤالٌ لا شأن له به.
abstract interface class LocalDataWiper {
  /// يمحو كل ما بالجهاز من بيانات الحساب — **ولا يمسّ تفضيلات الجهاز**.
  ///
  /// الثيم واللغة والخط ومعرّف الجهاز تخصّ الجهاز لا الحساب، ومسحُها يجعل
  /// الخروجَ يُعيد التطبيق إلى الإنجليزية والوضع الفاتح. ولهذا بالذات
  /// **`StorageService.clear()` ممنوعة** بهذا المستودع: من يملك مفاتيح يمسحها
  /// واحداً واحداً.
  ///
  /// **ولا يرمي.** الفشل هنا يقع بلحظةٍ لا تحتمل التوقّف — بين مستخدمٍ خرج
  /// وآخر يدخل — ورميةٌ تُبقي الجهاز بحالةٍ نصف ممحوّة بلا أن يعرف أحد. يُسجَّل
  /// ويمضي.
  Future<void> wipeAll();
}

/// جوابُ تطبيقٍ لا يحمل بياناتٍ محلية: لا شيء ليُمحى.
class NoLocalDataWiper implements LocalDataWiper {
  const NoLocalDataWiper();

  @override
  Future<void> wipeAll() async {}
}
