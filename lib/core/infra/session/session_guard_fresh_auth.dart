import 'package:injectable/injectable.dart';

/// **رايةُ «هذا الدخول أثبت حضور صاحبه للتوّ»** — تُرفع بعد تسجيل دخولٍ حيّ
/// (كلمة مرور كُتبت الآن)، وتُقرأ مرّةً واحدة عند تركيب الغلاف.
///
/// ## لماذا هذه الراية تحديداً
///
/// `SessionGuardCubit` يقفل الجلسة افتراضياً عند أوّل تركيبٍ لها — وهذا صحيحٌ
/// **إلا** في حالة واحدة: مستخدمٌ كتب كلمة مروره للتوّ بشاشة الدخول. مطالبتُه
/// برقم قفلٍ إضافي بعد ثوانٍ من كتابة كلمة مرور كاملة تجربةٌ سيئة بلا مبرّر
/// أمنيّ — فهو أثبت هويته توّاً بأقوى دليلٍ ممكن.
///
/// أما إقلاعٌ باردٌ يستعيد توكناً محفوظاً (`StartupResolver`) فلا يمرّ من هنا
/// إطلاقاً — لا رافعَ يُنادى، فتبقى الجلسة مقفولة حتى يُثبت المستخدم حضوره
/// بالقفل نفسه. **وهذا الفرق هو بيت القصيد.**
///
/// نفس نمط [WelcomeGreeting] حرفياً وللسبب نفسه: الرافع (`LoginCubit`) ينتهي
/// عمرُه بـ`replaceAll` قبل أن تُركَّب القشرة التي تقرأ — فرايةٌ لا معاملُ مسار.
@lazySingleton
class SessionGuardFreshAuth {
  bool _pending = false;

  /// يُنادى فور نجاح تسجيل الدخول بكلمة مرور — لا عند استعادة توكنٍ محفوظ.
  void raise() => _pending = true;

  /// يأخذ الراية **ويُنزلها** — `true` مرّةً واحدة لا غير.
  bool take() {
    final pending = _pending;
    _pending = false;
    return pending;
  }
}
