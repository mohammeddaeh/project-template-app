import 'package:injectable/injectable.dart';

/// **رايةُ ترحيبٍ لمرّةٍ واحدة** — تُرفع بشاشة التجهيز، وتُقرأ عند تركيب القشرة.
///
/// ## العطل الذي وُلدت منه
///
/// أولُ ما يستقبل الداخلَ بعد تسجيل الدخول كان **«تم تحديث بياناتك — ٨
/// تغييراً»**: حصيلةُ الجرد الأوّل يبثّها `SyncCheckReporter`، فيلتقطها
/// `SyncCheckAnnouncer` عند تركيب الغلاف. والعددُ صحيح والجملةُ كاذبة — «تحديث»
/// يقتضي سابقاً يُحدَّث، ولم يكن على الجهاز صفٌّ واحد. وهي فوق ذلك **معادة**:
/// شاشةُ التجهيز عرضت الجرد سطراً سطراً، وضغط المستخدم «موافق» عليه قبل ثانية.
///
/// فصار الجردُ الأوّل يُبتلع عند مصدره (بشاشة التجهيز)، وترتفع
/// هذه الرايةُ مكانه — فيُستقبل الداخلُ بما يعنيه وصولُه فعلاً: جهازُك جاهز،
/// واعمل من هنا بلا إنترنت.
///
/// ## ولماذا رايةٌ لا معاملُ مسار
///
/// نفس علّة `SyncCheckReporter` حرفاً بحرف: الرافعُ — شاشةُ التجهيز — ينتهي
/// بـ`replaceAll` **قبل** أن تُركَّب القشرة التي تقرأ. والترحيبُ حدثُ جلسةٍ لا
/// صفةَ وجهة: `MainShellRoute` يُبنى من خمسة مواضع (سبلاش · تجهيز · خروجٌ من
/// استمارة …)، وأربعةٌ منها `const` لا شأن لها بترحيب.
///
/// ⚠️ **و[take] تمحو**: القشرة تُعاد بناؤها لأسبابٍ شتّى، وترحيبٌ يتكرّر بكل
/// إعادةِ بناءٍ ضجيجٌ لا حفاوة.
@lazySingleton
class WelcomeGreeting {
  bool _pending = false;

  /// يُنادى بعد جردٍ أوّلٍ اكتمل على جهازٍ لم يكن لهذا الحساب عليه شيء.
  void raise() => _pending = true;

  /// يأخذ الراية **ويُنزلها** — `true` مرّةً واحدة لا غير.
  bool take() {
    final pending = _pending;
    _pending = false;
    return pending;
  }
}
